use crate::{EsmError, EsmReader, RefId, esm_record::EsmRecord, types::enums::RecInt};
use esm_parser_macros::LoadSave;
use glam::{IVec2, IVec3};

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Pathgrid {
    pub cell: RefId,
    pub data: PathgridData,
    pub points: Vec<PathgridPoint>,
    pub edges: Vec<PathgridEdge>,
}

impl EsmRecord for Pathgrid {
    fn id(&self) -> &RefId {
        &self.cell
    }
    const RECORD_ID: RecInt = RecInt::Pgrd;
}

impl Pathgrid {
    pub fn load(reader: &mut EsmReader, is_deleted: &mut bool) -> Result<Self, EsmError> {
        *is_deleted = false;
        let mut pathgrid = Pathgrid::default();
        let mut has_data = false;
        let mut edge_count = 0usize;

        while reader.has_more_subs() {
            let sub_name = reader.get_or_read_sub_name()?;

            match sub_name.as_bytes() {
                b"NAME" => {
                    pathgrid.cell = reader.read_refid()?;
                }
                b"DATA" => {
                    pathgrid.data = reader.read_typed_header_load()?;
                    has_data = true;
                }
                b"PGRP" => {
                    reader.read_sub_header()?;
                    let size = reader.context.remaining_subrec_data;
                    let expected_size =
                        size_of::<PathgridPoint>() as u32 * pathgrid.data.points as u32;
                    if size != expected_size {
                        return Err(reader.fail("Path point subrecord size mismatch"));
                    } else {
                        pathgrid.points.reserve(pathgrid.data.points as usize);
                        for _ in 0..pathgrid.data.points {
                            let point: PathgridPoint = reader.load()?;
                            edge_count += point.connection_num as usize;
                            pathgrid.points.push(point);
                        }
                    }
                }
                b"PGRC" => {
                    reader.read_sub_header()?;
                    let size = reader.context.remaining_subrec_data;
                    if size % size_of::<u32>() as u32 != 0 {
                        return Err(reader.fail("PGRC size not a multiple of 4"));
                    } else {
                        let raw_conn_num = size / size_of::<u32>() as u32;
                        let mut raw_connections = Vec::with_capacity(raw_conn_num as usize);
                        for _ in 0..raw_conn_num {
                            let current_value: u32 = reader.load()?;
                            raw_connections.push(current_value as usize);
                        }

                        let mut raw_it = raw_connections.iter();
                        let mut point_index = 0;
                        pathgrid.edges.reserve(edge_count);
                        for point in &pathgrid.points {
                            let connection_num = point.connection_num as usize;
                            // Fixed: check remaining iterator length instead of consumed length
                            if raw_it.len() < connection_num {
                                return Err(reader.fail("Not enough connections"));
                            }
                            for _ in 0..connection_num {
                                let edge = PathgridEdge {
                                    v0: point_index,
                                    v1: *raw_it.next().unwrap(),
                                };
                                pathgrid.edges.push(edge);
                            }
                            point_index += 1;
                        }
                    }
                }
                b"DELE" => {
                    reader.skip_sub_header()?;
                    *is_deleted = true;
                }
                _ => {
                    return Err(reader.fail("Unknown subrecord"));
                }
            }
        }

        if !has_data {
            return Err(reader.fail("Missing DATA subrecord"));
        }

        Ok(pathgrid)
    }
}
#[derive(Clone, Debug, Default, PartialEq, LoadSave)]
pub struct PathgridData {
    pub pos: IVec2,
    pub granularity: i16,
    pub points: u16,
}

#[derive(Clone, Debug, Default, PartialEq, LoadSave)]
#[repr(C)]
pub struct PathgridPoint {
    pub pos: IVec3,
    pub autogenerated: u8,
    pub connection_num: u8,
    // Note: C++ struct alignment includes 2 bytes of padding here to match 16-byte layout boundaries
    pub _padding: [u8; 2],
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct PathgridEdge {
    pub v0: usize,
    pub v1: usize,
}
