// src/pathgrid.rs

use crate::esm_reader::{EsmError, EsmReader};
use crate::refid_types::RefId;

#[derive(Debug, Clone, Copy, Default, PartialEq)]
#[repr(C, packed)]
pub struct PathgridDataHeader {
    // DATA subrecord, matches OpenMW DATAstruct
    pub m_x: i32,           // Grid X coordinate
    pub m_y: i32,           // Grid Y coordinate
    pub m_granularity: i16, // Granularity with which the graph was autogenerated
    pub m_points: u16,      // Number of path points.
} // Total: 4 + 4 + 2 + 2 = 12 bytes

#[derive(Debug, Clone, Copy, Default, PartialEq)]
#[repr(C, packed)]
pub struct PathgridPoint {
    // PGRP subrecord data element, matches OpenMW Point struct (16 bytes)
    pub m_x: i32,
    pub m_y: i32,
    pub m_z: i32,
    pub m_autogenerated: u8,
    pub m_connection_num: u8, // Number of connections from this point
    pub m_padding: [u8; 2],   // To match OpenMW's decompose padding for 16 bytes total
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub struct PathgridEdge {
    // In-memory representation of an edge
    pub v0_index: usize, // Index of the first point (source)
    pub v1_index: usize, // Index of the second point (destination from PGRC list)
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Pathgrid {
    pub id: Option<RefId>, // Optional, usually for cell pathgrids (OpenMW: mCell)
    pub data_header: Option<PathgridDataHeader>,
    pub points: Vec<PathgridPoint>,
    pub edges: Vec<PathgridEdge>,
}

impl Pathgrid {
    pub fn new() -> Self {
        Default::default()
    }

    pub fn load(reader: &mut EsmReader) -> Result<Self, EsmError> {
        let mut pgrd = Pathgrid::new();
        let mut data_header_loaded: Option<PathgridDataHeader> = None;
        let mut edge_count_accumulator: usize = 0;
        let mut raw_connections: Option<Vec<u32>> = None;

        while reader.has_more_subs() {
            let sub_name = reader.get_sub_name()?;

            match &sub_name.m_data {
                b"NAME" => {
                    // In OpenMW, this is mCell (RefId to the cell this pathgrid is for)
                    pgrd.id = Some(reader.get_ref_id()?);
                }
                b"DATA" => {
                    reader.get_sub_header()?;
                    let expected_size = std::mem::size_of::<PathgridDataHeader>() as u32;
                    if reader.get_sub_size() != expected_size {
                        return Err(
                            reader.report_sub_size_mismatch(expected_size, reader.get_sub_size())
                        );
                    }
                    let header = reader.get_t::<PathgridDataHeader>()?;
                    pgrd.data_header = Some(header);
                    data_header_loaded = Some(header);
                }
                b"PGRP" => {
                    reader.get_sub_header()?;
                    let pgrp_block_size = reader.get_sub_size();
                    let header = data_header_loaded.ok_or_else(|| {
                        reader.fail("PGRD: PGRP subrecord found before DATA header")
                    })?;

                    let point_struct_size = std::mem::size_of::<PathgridPoint>() as u32;
                    let expected_pgrp_block_size = header.m_points as u32 * point_struct_size;

                    if pgrp_block_size != expected_pgrp_block_size {
                        let header_points = header.m_points;
                        return Err(reader.fail(&format!(
                            "PGRD record {:?}: PGRP data size mismatch. File PGRP size: {}, Expected from DATA: {} ({} points * {} bytes/point)",
                            pgrd.id, pgrp_block_size, expected_pgrp_block_size, header_points, point_struct_size
                        )));
                    }

                    if header.m_points > 0 {
                        pgrd.points.reserve(header.m_points as usize);
                        for _i in 0..header.m_points {
                            let point = reader.get_t::<PathgridPoint>()?;
                            edge_count_accumulator += point.m_connection_num as usize;
                            pgrd.points.push(point);
                        }
                    }
                }
                b"PGRC" => {
                    reader.get_sub_header()?;
                    let pgrc_block_size = reader.get_sub_size();
                    if pgrc_block_size % 4 != 0 {
                        // Connections are u32
                        return Err(reader.fail(&format!(
                            "PGRD record {:?}: PGRC data size {} is not a multiple of 4",
                            pgrd.id, pgrc_block_size
                        )));
                    }
                    let num_raw_connections = (pgrc_block_size / 4) as usize;
                    let mut temp_connections = Vec::with_capacity(num_raw_connections);
                    for _ in 0..num_raw_connections {
                        temp_connections.push(reader.get_t::<u32>()?);
                    }
                    raw_connections = Some(temp_connections);
                }
                _ => {
                    reader.skip_h_sub()?;
                }
            }
        }

        if pgrd.data_header.is_none() && !pgrd.points.is_empty() {
            return Err(reader.fail(&format!(
                "PGRD record {:?} has points but no DATA header",
                pgrd.id
            )));
        }

        // Reconstruct edges based on OpenMW logic
        if let Some(connections) = raw_connections {
            if !pgrd.points.is_empty() {
                pgrd.edges.reserve(edge_count_accumulator);
                let mut conn_iter = connections.iter();
                for (v0_idx, point) in pgrd.points.iter().enumerate() {
                    for _ in 0..point.m_connection_num {
                        if let Some(&v1_raw_idx) = conn_iter.next() {
                            // Ensure v1_raw_idx is within bounds of points list
                            if (v1_raw_idx as usize) < pgrd.points.len() {
                                pgrd.edges.push(PathgridEdge {
                                    v0_index: v0_idx,
                                    v1_index: v1_raw_idx as usize,
                                });
                            } else {
                                // Log warning or error for invalid edge index
                                // eprintln!("[PGRD WARNING] Invalid edge target index {} in pathgrid {:?} for point {}", v1_raw_idx, pgrd.id, v0_idx);
                            }
                        } else {
                            // Not enough connections in PGRC block as declared by points' mConnectionNum sum
                            return Err(reader.fail(&format!("PGRD record {:?}: Not enough connections in PGRC block. Expected sum from points: {}, found in PGRC: {}", pgrd.id, edge_count_accumulator, connections.len())));
                        }
                    }
                }
                if conn_iter.next().is_some() {
                    // More connections in PGRC than accounted for by points' mConnectionNum sum
                    // eprintln!("[PGRD WARNING] Extra connections found in PGRC block for pathgrid {:?}.", pgrd.id);
                }
            }
        } else if edge_count_accumulator > 0 {
            // Points declare connections, but no PGRC block found
            return Err(reader.fail(&format!(
                "PGRD record {:?}: Points declare connections but PGRC subrecord is missing.",
                pgrd.id
            )));
        }

        Ok(pgrd)
    }
}
